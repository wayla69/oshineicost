ALLI = DATA["high_pop_high_cost"] + DATA.get("buffet_items", [])
def _find(sub):
    return next((it for it in ALLI if sub in it["description"]), None)
def _agg(subs):
    its = [_find(s) for s in subs]; its = [i for i in its if i]
    if not its: return 0.0, 0.0
    return its[0]["unit_cost"], sum(i["qty"] for i in its)

