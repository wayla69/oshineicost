# --- build menu pillar (bottom-up, annual THB) from TRANSFORMS ---
_menu_terms = []   # (gross_annual, risk)
_det_menu = 0.0
for _e in TRANSFORMS:
    if "save_num" in _e:
        # #4 trim -> overlaps waste/yield ; #7 premium -> portion pillar : excluded from menu pillar
        continue
    _fu = _e.get("from_override", _agg(_e["src"])[0])
    _qty = _e.get("qty_override", _agg(_e["src"])[1])
    _tu = sum(c for _,_,c in _e["bom"] if isinstance(c,(int,float))) if _e["bom"] else 0.0
    _gross = _qty*(_fu-_tu)*ANN
    _dedup = 0.5 if _e["num"] in (12,) else 1.0     # #12 uses by-product (overlap yield)
    _gross *= _dedup
    _menu_terms.append((_gross, _e["risk"]))
    _det_menu += _gross
MENU_GROSS = _det_menu   # gross annual potential of recipe re-engineering

def _tri(a,m,b): return _rnd.triangular(a,b,m)

_rnd.seed(20260620)
