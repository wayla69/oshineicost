def tcard(num, title, sub, from_html, add_html, to_html, metrics, accept, accept_cls="green"):
    w('<div class="tcard">')
    w(f'<div class="th"><div class="tn">Transform #{num} — {title}</div><div class="ts">{sub}</div></div>')
    w('<div class="tb">')
    w('<div class="flow">')
    w(f'<div class="box from"><div class="bx-h">เมนูเดิม (ต้นทุนสูง)</div>{from_html}</div>')
    w('<div class="arrow">+</div>')
    w(f'<div class="box add"><div class="bx-h">ผสานของยอดนิยมต้นทุนต่ำ</div>{add_html}</div>')
    w('<div class="arrow">→</div>')
    w(f'<div class="box to"><div class="bx-h">เมนูใหม่ (ต้นทุนต่ำ)</div>{to_html}</div>')
    w('</div>')
    w('<div class="tmetrics">')
    for v,k,cls in metrics:
        w(f'<div class="tm"><div class="v {cls}">{v}</div><div class="k">{k}</div></div>')
    w('</div>')
    w(f'<div class="callout {accept_cls}" style="margin:.8em 0 0"><div class="ct" style="font-size:13px">'
      f'การยอมรับของลูกค้า</div><p style="margin-bottom:0;font-size:13px">{accept}</p></div>')
    w('</div></div>')

