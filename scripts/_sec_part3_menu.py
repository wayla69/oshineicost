RISK_TAG = {"ต่ำมาก":"green","ต่ำ":"green","กลาง":"s","สูง":"red"}

def tcard(num, title, sub, from_html, add_html, to_html, bom, bom_total,
          metrics, accept, accept_cls="green", cat="", risk="", bom_note=None):
    w('<div class="tcard">')
    rtag = (f'<span class="tag {RISK_TAG.get(risk,"")}" style="margin-left:6px">ความเสี่ยง {risk}</span>'
            if risk else '')
    ctag = f'<span class="tag">{cat}</span> ' if cat else ''
    w(f'<div class="th"><div class="tn">Transform #{num} — {title}{rtag}</div>'
      f'<div class="ts">{ctag}{sub}</div></div>')
    w('<div class="tb">')
    w('<div class="flow">')
    w(f'<div class="box from"><div class="bx-h">เมนูเดิม (ต้นทุนสูง)</div>{from_html}</div>')
    w('<div class="arrow">+</div>')
    w(f'<div class="box add"><div class="bx-h">ผสานของยอดนิยมต้นทุนต่ำ</div>{add_html}</div>')
    w('<div class="arrow">→</div>')
    w(f'<div class="box to"><div class="bx-h">เมนูใหม่ (ต้นทุนต่ำ)</div>{to_html}</div>')
    w('</div>')
    # ---- detailed proposed BOM ----
    if bom:
        w('<div style="margin-top:.6em">')
        w('<div style="font-weight:700;font-size:10.5px;text-transform:uppercase;letter-spacing:.5px;'
          'color:var(--teal-d);margin:.2em 0 .25em">สูตรเสนอ — วัตถุดิบหลักต่อ 1 ที่ (ประมาณ)</div>')
        w('<table style="margin:.15em 0;font-size:11.5px"><thead><tr><th>วัตถุดิบ</th>'
          '<th class="r">ปริมาณ</th><th class="r">ต้นทุน</th></tr></thead><tbody>')
        for ing, qty, cost in bom:
            cd = f'฿{cost:.1f}' if isinstance(cost,(int,float)) else cost
            w(f'<tr><td>{ing}</td><td class="r">{qty}</td><td class="r">{cd}</td></tr>')
        w(f'<tr class="tot"><td>รวมต้นทุนเมนูใหม่</td><td class="r"></td>'
          f'<td class="r pos">{bom_total}</td></tr>')
        w('</tbody></table>')
        if bom_note:
            w(f'<p class="small" style="margin:-.2em 0 .2em">{bom_note}</p>')
        w('</div>')
    w('<div class="tmetrics">')
    for v,k,cls in metrics:
        w(f'<div class="tm"><div class="v {cls}">{v}</div><div class="k">{k}</div></div>')
    w('</div>')
    w(f'<div class="callout {accept_cls}" style="margin:.8em 0 0"><div class="ct" style="font-size:13px">'
      f'การยอมรับของลูกค้า</div><p style="margin-bottom:0;font-size:13px">{accept}</p></div>')
    w('</div></div>')

