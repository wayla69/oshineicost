"""Compose docs/ui-kit/colors_and_type.css for the formal theme (the UI kit's one stylesheet).

  tokens.css (the app's tokens, @import)            - what the live app uses
+ tokens design-system/tokens.json has and tokens.css lacks (generated, light + body.dark)
+ design-system/components/bundle.css               - the formal components, app class names
                                                      ([data-theme="dark"] -> body.dark)
+ kit layout helpers (app shell, grids, spacing)    - restyled to the formal rules
"""
import json, re
from pathlib import Path
R = str(Path(__file__).resolve().parent.parent) + '/'   # repo root
# usage: py -3.12 scripts/build_ui_kit_css.py   (after changing tokens.css, design-system/tokens.json or bundle.css)
tok_css = open(R + 'docs/ui-kit/tokens.css', encoding='utf-8').read()
have = set(re.findall(r'(--[A-Za-z0-9-]+)\s*:', tok_css))
t = json.load(open(R + 'design-system/tokens.json', encoding='utf-8'))
bundle = open(R + 'design-system/components/bundle.css', encoding='utf-8').read()

def val(v):
    # a design-system alias "{other-token}" is a CSS variable reference
    m = re.fullmatch(r'\{([A-Za-z0-9_.-]+)\}', v) if isinstance(v, str) else None
    return f'var(--{m.group(1)})' if m else v

light, dark, alias = [], [], []
for x in t['color']['tokens']:
    n = '--' + x['name']
    if n in have:
        continue
    v = x['value']
    lv = val(v.get('light') if isinstance(v, dict) else v)
    dv = val(v.get('dark', v.get('light')) if isinstance(v, dict) else v)
    if lv.startswith('var(') and lv == dv:
        alias.append(f'  {n}: {lv};')
        continue
    light.append(f'  {n}: {lv};')
    if dv != lv:
        dark.append(f'  {n}: {dv};')
for fam in ('spacing', 'radius', 'shadow', 'size', 'zIndex'):
    for x in (t.get(fam) or {}).get('tokens', []):
        n = '--' + x['name']
        if n in have:
            continue
        v = x['value']
        if isinstance(v, dict):   # per-theme value outside colour (e.g. focus-halo)
            light.append(f'  {n}: {val(v.get("light"))};')
            if v.get('dark') and v.get('dark') != v.get('light'):
                dark.append(f'  {n}: {val(v["dark"])};')
        else:
            light.append(f'  {n}: {val(v)};')
fams = t['type'].get('families', {})
for k, v in fams.items():
    if '--font-' + k not in have:
        light.append(f'  --font-{k}: {v};')

bundle = bundle.replace('[data-theme="dark"]', 'body.dark')
# the previews' stage helpers are design-system scaffolding, not kit components
bundle = re.sub(r'^\.ds-stage \{[^\n]*\n\.ds-col \{[^\n]*\n', '', bundle, flags=re.M)

head = '''/* ════════════════════════════════════════════════════════════════════════
   Oshinei UI Kit — colors_and_type.css  (formal theme, rebuilt 2026-10-01)

   GENERATED by composing three sources — edit those, then regenerate:
     1. tokens.css (@import)                    the app's own tokens, verbatim
     2. design-system/tokens.json               tokens the app inlines elsewhere
                                                (pills, quadrants, nav inks, group
                                                hues …), light + body.dark
     3. design-system/components/bundle.css     the formal components under the
                                                app's own class names
   plus the kit's layout helpers below. The direction: navy accent, 1px
   borders instead of shadows, 2–4px corners, flat colour (no gradients), no
   hover lifts, no emoji; KIRA UI. Group hues come from [data-group].

   OPTIONAL BRAND EXTENSION (--salmon, --salmon-deep, --teal) at the end is for
   marketing surfaces only (deck cover, hero) — never the dashboard.
   ════════════════════════════════════════════════════════════════════════ */
@import "tokens.css";
@import url("/vendor/kira-ui-font.css?v=7.0");   /* KIRA UI + Noto symbols, served without a login */

/* ── 2. tokens the app keeps outside tokens.css (from design-system/tokens.json) ── */
:root {
''' + '\n'.join(light) + '''
}
body.dark {
''' + '\n'.join(dark) + '''
}
/* aliases of other tokens: declared on both so they follow the theme in force */
:root, body.dark {
''' + '\n'.join(alias) + '''
}

/* ── 3. formal components (design-system/components/bundle.css) ── */
'''

helpers = '''

/* ── 4. kit layout helpers (the app shell, grids, spacing) ── */
.app-layout { display: flex; min-height: 100vh; }
.main-wrapper { flex: 1; display: flex; flex-direction: column; min-width: 0; }
.content-area { flex: 1; padding: 28px; }
.sidebar { align-self: stretch; }
.top-bar { position: sticky; top: 0; z-index: 40; }
.sample-note { font-size: 11px; color: var(--text-muted); border: 1px dashed var(--border-control); border-radius: var(--r-sm); padding: 4px 8px; display: inline-block; }
.grid { display: grid; gap: 16px; }
.g-2 { grid-template-columns: repeat(2, minmax(0, 1fr)); }
.g-3 { grid-template-columns: repeat(3, minmax(0, 1fr)); }
.g-4 { grid-template-columns: repeat(4, minmax(0, 1fr)); }
.g-5 { grid-template-columns: repeat(5, minmax(0, 1fr)); }
.flex { display: flex; } .between { justify-content: space-between; } .center { align-items: center; } .gap-2 { gap: 8px; } .gap-3 { gap: 12px; }
.mb-0 { margin-bottom: 0; } .mb-2 { margin-bottom: 8px; } .mb-3 { margin-bottom: 12px; } .mb-4 { margin-bottom: 16px; } .mb-5 { margin-bottom: 20px; }
.mt-2 { margin-top: 8px; } .mt-3 { margin-top: 12px; }
.chart-box { position: relative; height: 240px; }
@media (max-width: 1000px) { .g-3, .g-4, .g-5 { grid-template-columns: repeat(2, minmax(0, 1fr)); } }
@media (max-width: 640px) { .g-2, .g-3, .g-4, .g-5 { grid-template-columns: 1fr !important; } .sidebar { display: none; } .content-area { padding: 12px; } .subtab-bar { flex-wrap: wrap; } .content-area .card { overflow-x: auto; } }   /* !important: beats a page's inline column split */

/* ── OPTIONAL BRAND EXTENSION — marketing surfaces only, never the dashboard ── */
:root {
  --salmon:      #F97066;
  --salmon-deep: #E8685A;
  --teal:        #0D9488;
}
'''
open(R + 'docs/ui-kit/colors_and_type.css', 'w', encoding='utf-8', newline='\n').write(head + bundle.rstrip('\n') + helpers)
print('tokens added', len(light), 'dark overrides', len(dark))
