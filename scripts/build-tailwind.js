// Build vendor/tailwind.build.css: `npm run build:css` in tests/e2e (where tailwindcss is a devDependency).
// `npm run check:css` (= --check) rebuilds in memory and exits 1 when the committed file differs (CI, test.yml).
// The classes, the theme and the safelist live in tailwind.config.js; this script only decides HOW it is compiled,
// so that the result is the sheet the in-browser runtime (vendor/tailwind.js, the Play CDN build) used to make:
//   * Tailwind 3.4.17, the runtime's own version (pinned in tests/e2e/package.json);
//   * autoprefixer with the runtime's own browser list (RUNTIME_TARGETS, copied from vendor/tailwind.js) and
//     remove:false (the runtime keeps preflight's -moz-tab-size);
//   * NOT `tailwindcss --minify`: its cssnano merges and reorders rules (it moved white-space:nowrap out of .truncate
//     into a shared rule), which changes which rule wins a tie. Here only whitespace and comments are taken out.
// Rule order is Tailwind's canonical order (independent of which file names a class first) - the order the runtime
// gave every class it saw in one pass.
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const NM = [path.join(ROOT, 'tests', 'e2e'), ROOT];
const from = (m) => require(require.resolve(m, { paths: NM }));
const postcss = from('postcss');
const tailwindcss = from('tailwindcss');
const peers = require(path.join(path.dirname(require.resolve('tailwindcss/package.json', { paths: NM })), 'peers', 'index.js'));

const INPUT = path.join(ROOT, 'scripts', 'tailwind.input.css');
const OUTPUT = path.join(ROOT, 'vendor', 'tailwind.build.css');
const RUNTIME_TARGETS = ['and_chr 114', 'and_uc 15.5', 'chrome 114', 'chrome 113', 'chrome 109', 'edge 114', 'firefox 114',
  'ios_saf 16.5', 'ios_saf 16.4', 'ios_saf 16.3', 'ios_saf 16.1', 'opera 99', 'safari 16.5', 'samsung 21'];

function squeeze(root) {
  root.walkComments((c) => c.remove());
  root.walk((n) => {
    n.raws.before = '';
    n.raws.after = '';
    if (n.type === 'decl') n.raws.between = ':';
    if (n.type === 'rule' || n.type === 'atrule') { n.raws.between = ''; n.raws.semicolon = false; }
    if (n.type === 'rule' && n.selector) n.selector = n.selector.replace(/,\n\s*/g, ',');   // Tailwind's one-selector-per-line layout
    if (n.type === 'atrule') n.raws.afterName = n.params ? ' ' : '';
  });
}

async function build() {
  const plugins = [tailwindcss(path.join(ROOT, 'tailwind.config.js')),
    peers.lazyAutoprefixer()({ overrideBrowserslist: RUNTIME_TARGETS, remove: false })];
  const result = await postcss(plugins).process(fs.readFileSync(INPUT, 'utf8'), { from: INPUT, to: OUTPUT });
  squeeze(result.root);
  const ver = from('tailwindcss/package.json').version;
  return `/*! Tailwind CSS v${ver} | MIT License | https://tailwindcss.com - GENERATED by scripts/build-tailwind.js from tailwind.config.js: do not edit, run \`npm run build:css\` in tests/e2e */\n`
    + result.root.toString() + '\n';
}

process.env.BROWSERSLIST_IGNORE_OLD_DATA = '1';   // the targets are fixed above; the age of the caniuse data is irrelevant
build().then((out) => {
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8').replace(/\r\n/g, '\n') : '';
    if (cur !== out) {
      console.error('vendor/tailwind.build.css is out of date: run `npm run build:css` in tests/e2e and commit the file.');
      process.exit(1);
    }
    console.log('vendor/tailwind.build.css is up to date (' + out.length + ' bytes)');
    return;
  }
  fs.writeFileSync(OUTPUT, out);
  console.log('wrote vendor/tailwind.build.css (' + out.length + ' bytes)');
}).catch((e) => { console.error(e); process.exit(1); });
